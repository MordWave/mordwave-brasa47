import { BadRequestException, ConflictException, Injectable, Logger, NotFoundException } from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { type FindOptionsWhere, ILike, Repository } from 'typeorm';
import type { QueryDeepPartialEntity } from 'typeorm/query-builder/QueryPartialEntity.js';
import { resolveBusinessIdForRead } from '../auth/tenant.util.js';
import {
  PAGINATION_DEFAULT_LIMIT,
  PAGINATION_DEFAULT_PAGE,
} from '../common/pagination.const.js';
import { buildPaginated, escapeLikePattern, type Paginated } from '../common/pagination.util.js';
import type { SafeUser } from '../auth/safe-user.js';
import { businessLogoKey } from '../media/media-key.util.js';
import { ImageStorageService, type UploadableFile } from '../storage/image-storage.service.js';
import { UserRole } from '../user/user-role.enum.js';
import { businessInactiveError } from './business-active.js';
import { Business } from './business.entity.js';
import type { BusinessListRow } from './business.presenter.js';
import { BusinessListQueryDto } from './dto/business-list-query.dto.js';
import { BusinessQueryDto } from './dto/business-query.dto.js';
import { CreateBusinessDto } from './dto/create-business.dto.js';
import { UpdateBusinessDto } from './dto/update-business.dto.js';

const POSTGRES_UNIQUE_VIOLATION = '23505';
// UNIQUE(slug) on `businesses`, as created by the InitialSchema migration (TypeORM derives the name from the table and
// column, so it is the same in every environment). Identifying the constraint, not just the SQLSTATE, keeps any
// other unique violation from being reported as a taken slug.
const BUSINESS_SLUG_UNIQUE_CONSTRAINT = 'UQ_82ca19bc20713fdfa72626a5da0';

@Injectable()
export class BusinessService {
  private readonly logger = new Logger(BusinessService.name);

  constructor(
    @InjectRepository(Business)
    private readonly businessRepository: Repository<Business>,
    private readonly imageStorage: ImageStorageService,
  ) {}

  // Business has no "reassign to a different tenant" concept the way
  // Product/Category/Table do (resolveBusinessIdForUpdate exists for
  // exactly that, which doesn't apply here — there's no separate
  // "current" vs "requested" business, just "which one am I"). The read
  // resolver already expresses precisely that: an ADMIN's own businessId
  // always wins, a SUPER_ADMIN must say which one via ?businessId=. Used
  // for get/update/logo alike, since none of them "move" anything.
  private resolveTargetBusinessId(user: SafeUser, requestedBusinessId: string | undefined): string {
    const businessId = resolveBusinessIdForRead(user, requestedBusinessId);
    if (!businessId) {
      throw new BadRequestException(
        'businessId is required for a SUPER_ADMIN on this endpoint',
      );
    }
    return businessId;
  }

  private async findOrThrow(businessId: string): Promise<Business> {
    const business = await this.businessRepository.findOne({ where: { id: businessId } });
    if (!business) {
      throw new NotFoundException(`Business with id "${businessId}" not found`);
    }
    return business;
  }

  // GLOBAL listing for the SUPER_ADMIN business picker: one of the very few reads that is deliberately NOT
  // tenant-scoped, so it takes no user and never goes through the resolveBusinessIdFor* helpers (the controller's
  // @Roles(SUPER_ADMIN) is the gate). Paginated with a real total — businesses are few, the COUNT is cheap.
  // Only the columns a picker needs are selected (the storage key is selected only to build logoUrl in the
  // presenter and is never returned); no relations are loaded, so there is no N+1. `id` is the ORDER BY tiebreaker
  // so businesses sharing a name can never shuffle between pages. `search` is a parameterised ILIKE (TypeORM) on
  // name OR slug, with LIKE wildcards escaped.
  async findAll(query: BusinessListQueryDto): Promise<Paginated<BusinessListRow>> {
    const page = query.page ?? PAGINATION_DEFAULT_PAGE;
    const limit = query.limit ?? PAGINATION_DEFAULT_LIMIT;

    const filters: FindOptionsWhere<Business> = {};
    if (query.active !== undefined) filters.active = query.active;

    let where: FindOptionsWhere<Business> | FindOptionsWhere<Business>[] = filters;
    if (query.search) {
      const pattern = ILike(`%${escapeLikePattern(query.search)}%`);
      where = [
        { ...filters, name: pattern },
        { ...filters, slug: pattern },
      ];
    }

    const [items, total] = await this.businessRepository.findAndCount({
      select: { id: true, name: true, slug: true, active: true, logoStorageKey: true },
      where,
      order: { name: 'ASC', id: 'ASC' },
      skip: (page - 1) * limit,
      take: limit,
    });

    return buildPaginated(items, page, limit, total);
  }

  // SUPER_ADMIN-only creation. Not tenant-scoped (there is no tenant yet), so it takes no user: the controller's
  // @Roles(SUPER_ADMIN) is the gate. The id is generated by the database, never taken from the caller, and every
  // column the DTO does not carry is set explicitly: `active` true (the entity default — see the controller note),
  // no logo, no colours.
  //
  // A single INSERT ... RETURNING (`insert`, not `save`): one statement is atomic by itself — either the whole row
  // exists or nothing does — so it needs no explicit transaction, and the generated id, defaults and timestamps come
  // back from the same statement. `save` was deliberately not used: with concurrent requests failing on the same
  // slug it raised QueryRunnerAlreadyReleasedError (reproduced with plain repository calls, no HTTP, on the e2e
  // single-connection pool), whereas `insert` answers every loser with a clean 23505.
  //
  // Slug uniqueness is enforced by PostgreSQL's UNIQUE(slug), not by a read-then-write: two concurrent requests for
  // the same slug both attempt the INSERT, exactly one wins, and the loser's unique violation (23505) is turned
  // into a 409 here — only when the violated constraint is the slug's (see isSlugTaken); any other error, including
  // a different unique violation, is rethrown untouched.
  async create(dto: CreateBusinessDto): Promise<Business> {
    const business = this.businessRepository.create({
      name: dto.name,
      slug: dto.slug,
      active: true,
      address: dto.address ?? null,
      phone: dto.phone ?? null,
      hours: dto.hours ?? null,
      logoStorageKey: null,
      coverStorageKey: null,
      primaryColor: null,
      accentColor: null,
    });
    try {
      const result = await this.businessRepository.insert(business);
      return Object.assign(business, result.generatedMaps[0]);
    } catch (err) {
      if (this.isSlugTaken(err)) {
        throw new ConflictException({
          message: `A business with slug "${dto.slug}" already exists`,
          errorCode: 'BUSINESS_SLUG_TAKEN',
        });
      }
      throw err;
    }
  }

  // TypeORM's QueryFailedError copies the driver's `code` and `constraint` onto itself.
  private isSlugTaken(err: unknown): boolean {
    if (typeof err !== 'object' || err === null) return false;
    const { code, constraint } = err as { code?: unknown; constraint?: unknown };
    return code === POSTGRES_UNIQUE_VIOLATION && constraint === BUSINESS_SLUG_UNIQUE_CONSTRAINT;
  }

  async getMe(query: BusinessQueryDto, user: SafeUser): Promise<Business> {
    const businessId = this.resolveTargetBusinessId(user, query.businessId);
    return this.findOrThrow(businessId);
  }

  // The ONLY columns PATCH /businesses/me may write, whatever else the DTO class may grow: never slug, active, id or a storage key.
  private static readonly PROFILE_COLUMNS = ['name', 'address', 'phone', 'hours', 'primaryColor', 'accentColor'] as const;

  // WRITES OF A BUSINESS ROW (updateMe, uploadLogo). Two rules, both about concurrent writers:
  //
  // 1. COLUMN-SCOPED. Each write is ONE `UPDATE businesses SET <only the columns it changes> WHERE ...`. It never reads the row first and
  //    then saves that (possibly stale) copy: TypeORM's save() of an entity read earlier writes back EVERY column that differs from the
  //    row as it is now, so it restored an old cover / logo / colour / name — and even `active` (a suspension) — that another
  //    transaction had committed in between. A column nobody asked to change is simply not in the statement, so it cannot be reverted.
  //    Two writes that change the SAME column are last-writer-wins, as for any plain UPDATE.
  //
  // 2. ATOMIC STATE CHECK. An ADMIN may write only while their business is active. The JWT guard checked that when the request began;
  //    a suspension can start afterwards (and, for uploadLogo, while the image is being processed). So the condition travels INSIDE the
  //    statement: `... WHERE id = $1 AND active = true`. A concurrent suspension holds the row lock until it commits; this UPDATE waits
  //    for it and then re-evaluates the condition on the new version of the row, so it matches nothing (0 rows affected) instead of
  //    writing into a suspended business. A SUPER_ADMIN may edit the identity of a suspended business (as PATCH /businesses/:id), so
  //    their statement has no `active` condition. No explicit lock, timeout or new error code is involved.
  //
  // 0 rows affected is explained afterwards, with nothing written: no such business -> 404; suspended -> 403 BUSINESS_INACTIVE (the
  // same answer as the guard); anything else (reactivated in between) -> 409 BUSINESS_CONCURRENT_MODIFICATION, safe to repeat.
  private async writeColumns(businessId: string, user: SafeUser, columns: QueryDeepPartialEntity<Business>): Promise<void> {
    const where: FindOptionsWhere<Business> = user.role === UserRole.SUPER_ADMIN ? { id: businessId } : { id: businessId, active: true };
    const result = await this.businessRepository.update(where, columns);
    if ((result.affected ?? 0) > 0) return;

    const current = await this.businessRepository.findOne({ select: { id: true, active: true }, where: { id: businessId } });
    if (!current) throw new NotFoundException(`Business with id "${businessId}" not found`);
    if (!current.active) throw businessInactiveError();
    throw new ConflictException({
      message: 'This business was being changed at the same time; nothing was applied, review and retry',
      errorCode: 'BUSINESS_CONCURRENT_MODIFICATION',
    });
  }

  async updateMe(query: BusinessQueryDto, dto: UpdateBusinessDto, user: SafeUser): Promise<Business> {
    const businessId = this.resolveTargetBusinessId(user, query.businessId);

    // only the fields the request really carries (undefined = untouched; null = cleared on purpose; a string = the new value)
    const columns: QueryDeepPartialEntity<Business> = {};
    for (const field of BusinessService.PROFILE_COLUMNS) {
      const value = dto[field];
      if (value !== undefined) columns[field] = value;
    }

    if (Object.keys(columns).length > 0) await this.writeColumns(businessId, user, columns);
    return this.findOrThrow(businessId);
  }

  // New logo: upload to the bucket under a brand-new key (businesses/<id>/logo/
  // <uuid>.webp), THEN point the row at it with a statement that writes ONLY logo_storage_key (see writeColumns: nothing read before
  // the upload can be written back afterwards, and a business suspended meanwhile is not written to). The previous logo object is never
  // deleted here, and a failure after the upload only leaves a logged orphan candidate.
  async uploadLogo(query: BusinessQueryDto, user: SafeUser, file: UploadableFile): Promise<Business> {
    const businessId = this.resolveTargetBusinessId(user, query.businessId);
    const business = await this.findOrThrow(businessId);
    // cheap refusal BEFORE processing the image; the decisive check is the one inside the UPDATE below
    if (!business.active && user.role !== UserRole.SUPER_ADMIN) throw businessInactiveError();

    const storageKey = await this.imageStorage.upload(businessLogoKey(businessId), file);

    try {
      await this.writeColumns(businessId, user, { logoStorageKey: storageKey });
    } catch (error) {
      this.logger.error(`Logo uploaded but not saved; orphan candidate key=${storageKey}`);
      throw error;
    }
    return this.findOrThrow(businessId);
  }
}
